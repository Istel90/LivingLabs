import assert from 'node:assert/strict';
import { analysisJsonReplacer, restoreAnalysisPayload } from '../../riskmap-core-main/src/lib/data/analysisSerialization.js';
const input = { gridResult: { values: new Float32Array([0, NaN, .625]), validIndices: [0, 2] }, indicators: [{ gridValues: new Map([[0, 0], [600_001, .75]]) }] };
const json = JSON.stringify(input, analysisJsonReplacer);
const output = restoreAnalysisPayload(JSON.parse(json));
assert.deepEqual(output.gridResult.values, Array.from(input.gridResult.values));
assert.deepEqual(output.gridResult.validIndices, input.gridResult.validIndices);
assert.deepEqual(output.indicators, input.indicators);
const doubleSource = restoreAnalysisPayload(JSON.parse(JSON.stringify({gridValues:[0.123456789123]}, analysisJsonReplacer)));
assert.equal(doubleSource.gridValues[0], 0.123456789123);
const coast = new Float32Array(2_000_001).fill(Number.NaN);
coast[0] = 0; coast[2_000_000] = .875;
const compact = JSON.stringify({gridResult:{values:coast}}, analysisJsonReplacer);
assert.ok(compact.length < 200);
const restoredCoast = restoreAnalysisPayload(JSON.parse(compact)).gridResult.values;
assert.equal(restoredCoast.length, coast.length);
assert.equal(restoredCoast[0], 0); assert.equal(restoredCoast[2_000_000], .875);
assert.ok(Number.isNaN(restoredCoast[1]));
assert.ok(Number.isNaN(output.gridResult.values[1]));
assert.equal(output.indicators[0].gridValues.has(1), false);
assert.equal(output.indicators[0].gridValues.get(0), 0);
const legacy = restoreAnalysisPayload({ gridResult: { values: {'0': .2, '1': null, '2': .8} }, indicators: [{gridValues:{}}] });
assert.ok(legacy.gridResult.values instanceof Float32Array);
assert.ok(Number.isNaN(legacy.gridResult.values[1]));
assert.equal(legacy.indicators[0].gridValues, null);
console.log('Sparse/dense round trip, zero vs missing, and legacy draft restoration passed');
